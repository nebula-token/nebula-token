#!/usr/bin/env node
//
// scripts/build-traceability.mjs — generate spec/traceability.json.
//
//   node scripts/build-traceability.mjs          write the file
//   node scripts/build-traceability.mjs --check   fail if it is stale
//
// SPECIFICATION.md states: "The mapping from requirement to test is published in
// spec/traceability.json". That mapping is derived data — every fact in it
// already exists in the vectors — so it is generated rather than maintained,
// and scripts/validate-vectors.mjs fails the build when the checked-in file
// drifts from what the vectors say.
//
// A requirement with no citing vector is listed too, with an empty array. That
// is the useful half of the artefact: it shows exactly which requirements no
// vector or scenario cites. Note the boundary: a few of those — the constants
// block ([N-4]), clock injection ([N-3]), the error-code set ([N-38]) — are
// nonetheless asserted by every per-language conformance runner. An empty pair
// means "no citing vector", which is a weaker statement than "unexecuted", and
// the description emitted into the document says so.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * @param {{tv: object, bv: object, defined: Set<string>}} input
 * @returns {object} the traceability document
 */
export function build({ tv, bv, defined }) {
  /** @type {Map<string, {vectors: Set<string>, scenarios: Set<string>}>} */
  const rows = new Map();
  const row = (req) => {
    if (!rows.has(req)) rows.set(req, { vectors: new Set(), scenarios: new Set() });
    return rows.get(req);
  };
  for (const req of defined) row(req);

  // All three case sections, not just `parsing`. Reading one of them was the
  // reason [N-11] and [N-13] were published as "no citing vector" while
  // fourteen hashing vectors pinned them against fixed digests.
  for (const section of ["verifier_hashing", "device_hashing", "parsing"]) {
    for (const c of tv[section] ?? []) {
      if (c.rule) row(c.rule.split(".")[0]).vectors.add(c.id);
    }
  }
  for (const s of bv.scenarios ?? []) {
    for (const req of s.requirements ?? []) row(req).scenarios.add(s.id);
  }

  const byNumber = (a, b) => Number(a.slice(2)) - Number(b.slice(2));
  // Never the parameterless sort() (javascript:S2871): it coerces elements to
  // strings and orders them by UTF-16 code unit, which is an ordering this file
  // inherits by accident rather than chooses. byCodeUnit states it explicitly
  // and reproduces it exactly, so the generated document is unchanged — which
  // matters, because validate-vectors.mjs fails when it drifts. localeCompare
  // would have been the wrong "fix": it varies with the runtime's locale, and a
  // generated artefact that reorders itself per machine is a broken gate.
  const byCodeUnit = (a, b) => {
    if (a < b) return -1;
    return a > b ? 1 : 0;
  };
  const requirements = {};
  for (const req of [...rows.keys()].sort(byNumber)) {
    const { vectors, scenarios } = rows.get(req);
    requirements[req] = {
      vectors: [...vectors].sort(byCodeUnit),
      scenarios: [...scenarios].sort(byCodeUnit),
    };
  }

  const executed = Object.values(requirements).filter(
    (r) => r.vectors.length || r.scenarios.length,
  ).length;

  return {
    $comment:
      "GENERATED by scripts/build-traceability.mjs from spec/test-vectors.json and spec/behavior-vectors.json. Do not edit by hand; scripts/validate-vectors.mjs fails when this file is stale.",
    description:
      "Requirement-to-test traceability for NEBULA, published per SPECIFICATION.md. `vectors` are ids in spec/test-vectors.json, `scenarios` are ids in spec/behavior-vectors.json. An empty pair means no vector or scenario cites the requirement. Most such requirements govern API shape, documentation or deployment and cannot be expressed as a vector, and are verified by review; a few — the constants block ([N-4]), clock injection ([N-3]) and the error-code set ([N-38]) — are instead asserted by every per-language conformance runner, so an empty pair is a weaker statement than 'unexecuted'.",
    spec_version: tv.spec_version,
    counts: {
      requirements: Object.keys(requirements).length,
      executed,
      by_review: Object.keys(requirements).length - executed,
    },
    requirements,
  };
}

// ------------------------------------------------------------------ CLI

if (import.meta.url === `file://${process.argv[1].replaceAll("\\", "/")}` ||
    process.argv[1]?.endsWith("build-traceability.mjs")) {
  const readJson = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
  const spec = readFileSync(join(ROOT, "SPECIFICATION.md"), "utf8");
  const defined = new Set([...spec.matchAll(/\*\*\[(N-\d+)\]/g)].map((m) => m[1]));

  const doc = build({
    tv: readJson("spec/test-vectors.json"),
    bv: readJson("spec/behavior-vectors.json"),
    defined,
  });
  const text = JSON.stringify(doc, null, 2) + "\n";
  const target = join(ROOT, "spec/traceability.json");

  if (process.argv.includes("--check")) {
    let current = null;
    try {
      current = readFileSync(target, "utf8");
    } catch {
      console.error("spec/traceability.json is missing — run: node scripts/build-traceability.mjs");
      process.exit(1);
    }
    if (current.trim() !== text.trim()) {
      console.error("spec/traceability.json is stale — run: node scripts/build-traceability.mjs");
      process.exit(1);
    }
    console.log(`spec/traceability.json is up to date (${doc.counts.requirements} requirements, ${doc.counts.executed} executed)`);
  } else {
    writeFileSync(target, text);
    console.log(`wrote spec/traceability.json — ${doc.counts.requirements} requirements, ${doc.counts.executed} executed by vectors, ${doc.counts.by_review} by review`);
  }
}
